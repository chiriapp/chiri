import type DatabasePlugin from '@tauri-apps/plugin-sql';
import { describe, expect, it, vi } from 'vitest';
import { createTag } from '$lib/database/tags';

describe('database tag creation', () => {
  it('preserves the ID generated by the store', async () => {
    const connection = {
      select: vi.fn().mockResolvedValue([{ max_order: 0 }]),
      execute: vi.fn().mockResolvedValue(undefined),
    } as unknown as DatabasePlugin;

    const tag = await createTag(connection, {
      id: 'store-tag-id',
      name: 'bulk-profile',
      color: '#f085cc',
      sortOrder: 100,
    });

    expect(tag.id).toBe('store-tag-id');
    expect(connection.execute).toHaveBeenCalledWith(expect.any(String), [
      'store-tag-id',
      'bulk-profile',
      '#f085cc',
      null,
      null,
      100,
    ]);
  });
});
